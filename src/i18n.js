function useI18n() {
  const [lang, setLangState] = React.useState(() => {
    const stored = localStorage.getItem('smartops.lang');
    if (stored === 'es' || stored === 'es-ES') return 'es-ES';
    if (stored === 'en' || stored === 'en-GB') return 'en-GB';
    return 'es-ES';
  });

  const setLang = React.useCallback((code) => {
    const normalized = code === 'es' || code === 'es-ES' ? 'es-ES' : 'en-GB';
    localStorage.setItem('smartops.lang', normalized === 'es-ES' ? 'es' : 'en');
    setLangState(normalized);
    document.documentElement.lang = normalized === 'es-ES' ? 'es' : 'en';
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = lang === 'es-ES' ? 'es' : 'en';
  }, [lang]);

  const t = TRANSLATIONS[lang] || TRANSLATIONS['es-ES'];
  return { lang, setLang, t };
}

Object.assign(window, { TRANSLATIONS, useI18n });
